import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { once } from 'node:events';
import { mkdtemp, mkdir, realpath, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createInterface } from 'node:readline';
import { chromium } from '@playwright/test';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const python = process.env.SUPPORTOID_TEST_PYTHON ?? resolve(root, process.platform === 'win32' ? '.venv/Scripts/python.exe' : '.venv/bin/python');
const directory = await mkdtemp(resolve(tmpdir(), 'supportoid-browser-'));
const output = resolve(root, 'test-results/browser');
await mkdir(output, { recursive: true });
const service = spawn(python, ['-m', 'scripts.browser_runtime', directory], { cwd: root, windowsHide: true, env: { ...process.env, SUPPORTOID_TEST_NODE: process.execPath }, stdio: ['pipe', 'pipe', 'pipe'] });
let stderr = '';
service.stderr.on('data', (chunk) => { stderr += chunk.toString(); });
const lines = createInterface({ input: service.stdout });
let browser;
try {
  const descriptor = await new Promise((accept, reject) => {
    const timer = setTimeout(() => reject(new Error(`Local services timed out: ${stderr}`)), 180000);
    service.once('exit', () => { clearTimeout(timer); reject(new Error(`Local services exited: ${stderr}`)); });
    lines.on('line', (line) => {
      try { const value = JSON.parse(line); if (value.url) { clearTimeout(timer); accept(value); } } catch { /* Startup diagnostics are not JSON descriptors. */ }
    });
  });
  browser = await chromium.launch({ channel: process.env.PLAYWRIGHT_CHANNEL, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto(descriptor.url + '/login');
  await page.getByLabel('Username', { exact: true }).fill('browser-admin');
  await page.getByLabel('Password', { exact: true }).fill('wrong-password');
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Invalid credentials' }).waitFor();
  const outage = (route) => route.abort('failed');
  await page.route('**/api/v1/auth/login', outage);
  await page.getByLabel('Password', { exact: true }).fill('synthetic-browser-password');
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'temporarily unavailable' }).waitFor();
  await page.unroute('**/api/v1/auth/login', outage);
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await page.waitForURL('**/dashboard');
  await page.reload();
  await page.getByRole('link', { name: 'Chat', exact: true }).click();
  await page.route('**/api/v1/chat', async (route) => { await new Promise((accept) => setTimeout(accept, 500)); await route.continue(); });
  await page.getByLabel('Chat message').fill('How do I reset my password?');
  const response = page.waitForResponse('**/api/v1/chat');
  await page.getByRole('button', { name: 'Send message' }).click();
  await page.getByLabel('Chat message').fill('Unsent follow-up');
  const reply = await (await response).json();
  await page.getByRole('button', { name: 'Helpful response', exact: true }).waitFor();
  assert.equal(await page.getByLabel('Chat message').inputValue(), 'Unsent follow-up');
  await page.getByText('How do I reset my password?', { exact: true }).waitFor();
  await page.route('**/api/v1/feedback', outage);
  await page.getByRole('button', { name: 'Helpful response', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Feedback could not be recorded' }).waitFor();
  await page.unroute('**/api/v1/feedback', outage);
  await page.getByRole('button', { name: 'Helpful response', exact: true }).click();
  await page.getByRole('status').filter({ hasText: 'Feedback recorded' }).waitFor();
  await page.unroute('**/api/v1/chat');
  await page.route('**/api/v1/chat', outage);
  await page.getByRole('button', { name: 'Send message' }).click();
  await page.getByRole('alert').filter({ hasText: 'could not be sent' }).waitFor();
  assert.equal(await page.getByLabel('Chat message').inputValue(), 'Unsent follow-up');
  await page.unroute('**/api/v1/chat', outage);
  await page.reload();
  await page.getByText(reply.conversation_id, { exact: true }).waitFor();
  await page.getByLabel('Chat message').fill('Can you give me the next step?');
  const followup = page.waitForRequest('**/api/v1/chat');
  await page.getByRole('button', { name: 'Send message' }).click();
  assert.equal((await followup).postDataJSON().conversation_id, reply.conversation_id);
  await page.getByRole('button', { name: 'Helpful response', exact: true }).waitFor();
  await page.screenshot({ path: resolve(output, 'chat-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: resolve(output, 'chat-mobile.png'), fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile page fits its viewport');
  await page.route('**/api/v1/auth/logout', outage);
  await page.getByRole('button', { name: 'Sign out' }).click();
  await page.getByRole('alert').filter({ hasText: 'Could not sign out' }).waitFor();
  await page.unroute('**/api/v1/auth/logout', outage);
  const sync = await page.evaluate(async () => {
    const csrf = document.cookie.match(/(?:^|;\s*)csrf_token=([^;]*)/)?.[1] ?? '';
    const response = await fetch('/api/v1/sync', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': decodeURIComponent(csrf) }, body: JSON.stringify({ limit: 50 }) });
    return response.status;
  });
  assert.equal(sync, 200);
  const traces = await (await page.request.get(descriptor.adapterUrl + '/data/traces', { headers: descriptor.adapterHeaders })).json();
  assert.ok(traces.traces.length > 0, 'application sync reaches the real local adapter');
  await page.getByRole('button', { name: 'Sign out' }).click();
  await page.waitForURL('**/login');
  assert.equal((await page.request.get(descriptor.url + '/api/v1/auth/me')).status(), 401);
  await page.getByLabel('Username', { exact: true }).fill('browser-support');
  await page.getByLabel('Password', { exact: true }).fill('synthetic-support-password');
  await page.getByRole('button', { name: 'Sign In', exact: true }).click();
  await page.waitForURL('**/dashboard');
  assert.equal(await page.getByRole('link', { name: 'Operations', exact: true }).count(), 0);
  assert.equal((await page.request.get(descriptor.url + '/api/v1/admin/security/report')).status(), 403);
  assert.deepEqual(errors, []);
  console.log('PASS: built React, bootstrap/login/auth restore, chat draft/conversation restore, feedback, recoverable outages, denied admin, sync to local adapter, logout and desktop/mobile; zero page errors.');
} finally {
  await browser?.close();
  lines.close();
  service.stdin.end();
  if (service.exitCode === null) await once(service, 'exit');
  const resolvedDirectory = await realpath(directory);
  assert.ok(resolvedDirectory.startsWith((await realpath(tmpdir())) + sep), 'cleanup remains under the temporary root');
  await rm(resolvedDirectory, { recursive: true, force: true });
}
